const I18n = (() => {
  const WORDS = OHARA_WORDS;
  let lang = "fr";
  try {
    lang = localStorage.getItem("ohara-lang") === "en" ? "en" : "fr";
  } catch {}

  const words = () => WORDS[lang];
  function set(next) {
    lang = next === "en" ? "en" : "fr";
    try {
      localStorage.setItem("ohara-lang", lang);
    } catch {}
    if (typeof document !== "undefined") document.documentElement.lang = lang;
  }
  return { words, set, get: () => lang, WORDS };
})();

if (typeof module !== "undefined") module.exports = I18n;
